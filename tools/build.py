"""Build the launcher's data: trd/<id>.md (front matter + Markdown) + audit.json + img/<id>.webp -> js/data.js
(window.LAUNCHER), so index.html works from file:// too (no fetch).
uv run --with markdown python tools/build.py
"""
import json, pathlib, re
import markdown

ROOT = pathlib.Path(__file__).resolve().parent.parent
ORDER = ['phonics-run', 'puzzle', 'eye-catch', 'toy-catch', 'croco', 'phonics-match', 'magic-block', 'ring-ding-dong', 'word-mashup']
# newest game first (user 2026-11-24 "최근에 만든게 제일 리스트 위로 오게"): a new game goes at the FRONT of ORDER and of
# audit.json "games". Cards are numbered 01… in this order, and the featured strip starts with the first one.
FALLBACK = {   # used until a game's TRD exists
    'eye-catch': ('Eye Catch', '아이캐치', 'https://jinilee-hue.github.io/Eye-Catch/'),
    'magic-block': ('Magic Block', '매직 블록', 'https://jinilee-hue.github.io/Magic-Block/'),
    'phonics-match': ('Phonics Match', '파닉스 매치', 'https://jinilee-hue.github.io/Phonics-Match/'),
    'croco': ('Croco Phonics', '크로코 파닉스', 'https://jinilee-hue.github.io/Croco-Phonics/'),
    'word-mashup': ('Word Mashup 3D', '워드 매시업', 'https://jinilee-hue.github.io/phonics-wordmashup-3D/'),
    'toy-catch': ('Toy Catch', '토이캐치', 'https://jinilee-hue.github.io/Toy-Catch/'),
    'ring-ding-dong': ('Ring Ding Dong', '링딩동', 'https://jinilee-hue.github.io/Phonics-Halli-Galli-3D/'),
    'puzzle': ('Phonics Puzzle', '파닉스 퍼즐', 'https://jinilee-hue.github.io/Phonics-Puzzle/'),
    'phonics-run': ('Phonics Run', '파닉스 런', 'https://jinilee-hue.github.io/Phonics-Run/'),
}


def parse(path):
    text = path.read_text(encoding='utf-8')
    meta, body = {}, text
    m = re.match(r'^---\n(.*?)\n---\n(.*)$', text, re.S)
    if m:
        for line in m.group(1).splitlines():
            if ':' in line:
                k, v = line.split(':', 1)
                meta[k.strip()] = v.strip().strip('"')
        body = m.group(2)
    body = re.sub(r'^# .*\n', '', body, count=1)           # the page shows its own title
    toc = []

    def hid(mm):
        name = re.sub(r'^\d+\.\s*', '', mm.group(1)).strip()
        toc.append(name)
        return '<h2 id="s%d"><span class="no">%d</span>%s</h2>' % (len(toc), len(toc), name)
    html = markdown.markdown(body, extensions=['tables', 'sane_lists'])
    html = re.sub(r'<h2>(.*?)</h2>', hid, html)
    html = html.replace('<table>', '<div class="tbl"><table>').replace('</table>', '</table></div>')
    # priority tags in section 12
    cls = {'높음': 'hi', '중간': 'mid', '낮음': 'lo', '반영': 'done'}   # [반영] = fixed (and live)
    html = re.sub(r'\[(높음|중간|낮음|반영)\]', lambda mm: '<b class="pri p-%s">%s</b>' % (cls[mm.group(1)], mm.group(1)), html)
    return meta, html, toc


games = []
for gid in ORDER:
    f = ROOT / 'trd' / f'{gid}.md'
    t, tk, url = FALLBACK[gid]
    g = {'id': gid, 'title': t, 'title_ko': tk, 'url': url, 'img': f'img/{gid}.webp', 'html': '', 'toc': [], 'has_trd': False}
    if f.exists():
        meta, html, toc = parse(f)
        g.update({k: v for k, v in meta.items() if v and not v.startswith('<')})
        g.update({'html': html, 'toc': toc, 'has_trd': True, 'id': gid})
    games.append(g)
audit = json.loads((ROOT / 'audit.json').read_text(encoding='utf-8'))
(ROOT / 'js/data.js').write_text('/* generated by tools/build.py — do not edit */\nwindow.LAUNCHER = '
                                 + json.dumps({'games': games, 'audit': audit}, ensure_ascii=False) + ';\n', encoding='utf-8')
print('games', len(games), '| TRDs', sum(g['has_trd'] for g in games), '| criteria', len(audit['criteria']), '| fixes', len(audit['fixes']))
